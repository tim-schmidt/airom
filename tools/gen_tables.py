#!/usr/bin/env python3
"""Generate AIrom's static data tables from the Umoria 5.6 C sources.

The object and monster tables are ~700 rows of C struct initialisers. Hand
transcription would be both tedious and unverifiable, so they are generated
instead: this script is the record of how each C field maps to each C# field,
and re-running it against the reference sources reproduces the output exactly.

Usage:
    python tools/gen_tables.py [--moria PATH] [--check]

--check regenerates into memory and fails if the committed files differ,
which is what CI would run to prove the tables were not hand-edited.
"""


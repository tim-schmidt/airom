def _emit_rows(lines, declaration, kind, expected, fields, text, defines, doc):
    body = extract_initialiser(text, declaration)
    rows = split_rows(body)
    if len(rows) != expected:
        raise SystemExit(
            "{0}: parsed {1} rows, expected {2}".format(declaration, len(rows), expected)
        )

    lines.extend(doc)
    lines.append(
        "    public static readonly {0}[] {1} = new {0}[{2}]".format(kind[0], kind[1], expected)
    )
    lines.append("    {")

    for index, row in enumerate(rows):
        f = split_fields(row)
        if len(f) != fields:
            raise SystemExit(
                "{0} row {1}: expected {2} fields, got {3}".format(
                    declaration, index, fields, len(f)
                )
            )
        values = [c_string(f[0])]
        values += [str(c_number(x, defines)) for x in f[1:]]
        lines.append("        new(" + ", ".join(values) + "),")

    lines += ["    };", ""]


def gen_player(moria):
    text, defines = _player_source(moria)

    lines = [
        HEADER.format(source="moria/source/player.c"),
        "namespace Airom.Data;",
        "",
        "public static partial class GameTables",
        "{",
    ]

    _emit_rows(
        lines, "race[MAX_RACES]", ("RaceType", "Races"), defines["MAX_RACES"], 28,
        text, defines,
        [
            "    /// <summary>",
            "    /// The eight playable races. Each shifts the rolled stats and carries its",
            "    /// own build, lifespan and aptitudes.",
            "    /// </summary>",
        ],
    )

    _emit_rows(
        lines, "class[MAX_CLASS]", ("ClassType", "Classes"), defines["MAX_CLASS"], 18,
        text, defines,
        [
            "    /// <summary>",
            "    /// The six classes. Their stat adjustments are applied after the race's,",
            "    /// so a class can pull a stat back down that a race pushed up.",
            "    /// </summary>",
        ],
    )

    _emit_rows(
        lines, "background[MAX_BACKGROUND]", ("BackgroundType", "Backgrounds"),
        defines["MAX_BACKGROUND"], 5, text, defines,
        [
            "    /// <summary>",
            "    /// Fragments of a character's history, arranged as a set of linked charts.",
            "    /// Each entry names the chart it belongs to and the chart to continue with,",
            "    /// so rolling walks from one to the next until it runs out.",
            "    /// </summary>",
        ],
    )

    # The class titles are a class-by-level grid of strings.
    body = extract_initialiser(text, "player_title[MAX_CLASS][MAX_PLAYER_LEVEL]")
    rows = split_rows(body)
    if len(rows) != defines["MAX_CLASS"]:
        raise SystemExit(
            "player_title: parsed {0} rows, MAX_CLASS is {1}".format(
                len(rows), defines["MAX_CLASS"]
            )
        )

    lines += [
        "    /// <summary>",
        "    /// What a character of each class is called at each level, indexed",
        "    /// [class][level - 1]. The rank shown beside the race and class.",
        "    /// </summary>",
        "    public static readonly string[][] ClassTitles =",
        "    [",
    ]
    for row in rows:
        titles = [c_string(f) for f in split_fields(row) if f]
        if len(titles) != defines["MAX_PLAYER_LEVEL"]:
            raise SystemExit(
                "player_title row: expected {0} titles, got {1}".format(
                    defines["MAX_PLAYER_LEVEL"], len(titles)
                )
            )
        line = "        ["
        for title in titles:
            if len(line) + len(title) + 2 > 96:
                lines.append(line.rstrip())
                line = "            "
            line += title + ", "
        lines.append(line.rstrip().rstrip(",") + "],")
    lines += ["    ];", ""]

    # How much experience each level costs, before the class multiplier.
    body = extract_initialiser(text, "player_exp[MAX_PLAYER_LEVEL]")
    values = [str(c_number(f, defines)) for f in split_fields(body) if f]
    if len(values) != defines["MAX_PLAYER_LEVEL"]:
        raise SystemExit(
            "player_exp: parsed {0} entries, MAX_PLAYER_LEVEL is {1}".format(
                len(values), defines["MAX_PLAYER_LEVEL"]
            )
        )
    lines += [
        "    /// <summary>",
        "    /// Experience needed for each level, before the class multiplier is",
        "    /// applied. Mirrors player_exp[].",
        "    /// </summary>",
        "    public static readonly int[] PlayerExperience =",
        "    [",
    ]
    line = "        "
    for value in values:
        piece = value + ", "
        if len(line) + len(piece) > 96:
            lines.append(line.rstrip())
            line = "        "
        line += piece
    lines.append(line.rstrip().rstrip(","))
    lines += ["    ];", ""]

    # What each class gains per level at fighting, shooting, using a device,
    # disarming and saving. In player.c rather than tables.c, like the rest of
    # the player data.
    _emit_matrix(
        lines,
        "ClassLevelAdjust",
        "short",
        [
            "    /// <summary>",
            "    /// What each class gains per level, in the five things a level improves:",
            "    /// fighting, shooting, using a magical device, disarming, and saving",
            "    /// throws. Mirrors class_level_adj[][].",
            "    /// </summary>",
        ],
        _matrix(
            extract_initialiser(text, "class_level_adj[MAX_CLASS][MAX_LEV_ADJ]"),
            defines,
            defines["MAX_CLASS"],
            defines["MAX_LEV_ADJ"],
        ),
    )

    body = extract_initialiser(text, "player_init[MAX_CLASS][5]")
    rows = split_rows(body)
    lines += [
        "    /// <summary>",
        "    /// The five items each class starts with, as object table indices.",
        "    /// </summary>",
        "    public static readonly int[][] StartingItems =",
        "    [",
    ]
    for row in rows:
        values = [str(c_number(x, defines)) for x in split_fields(row) if x]
        lines.append("        [" + ", ".join(values) + "],")
    lines += ["    ];", ""]

    lines[-1:] = ["}", ""]
    return "\n".join(lines)



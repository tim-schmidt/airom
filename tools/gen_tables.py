def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--moria", type=Path, default=DEFAULT_MORIA)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if not (args.moria / "source" / "treasure.c").exists():
        print("reference sources not found under " + str(args.moria), file=sys.stderr)
        return 2

    repo = Path(__file__).resolve().parent.parent
    failed = False
    for relative, generate in TARGETS.items():
        content = generate(args.moria)
        path = repo / relative
        if args.check:
            existing = path.read_text(encoding="utf-8") if path.exists() else ""
            if existing.replace("\r\n", "\n") != content:
                print("STALE: " + relative, file=sys.stderr)
                failed = True
            else:
                print("ok: " + relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            print("wrote {0} ({1} lines)".format(relative, content.count("\n")))

    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
